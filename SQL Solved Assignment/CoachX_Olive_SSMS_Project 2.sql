-- Q1. What is the total sales revenue generated by each product?
SELECT p.product_name, SUM(p.price) AS total_revenue
FROM project.sales s
JOIN project.product p ON s.product_id = p.product_id
GROUP BY p.product_name
ORDER BY total_revenue DESC;

-- Q2. Which 3 products have the highest sales revenue?
SELECT TOP 3 p.product_name, SUM(p.price) AS total_revenue
FROM project.sales s
JOIN project.product p ON s.product_id = p.product_id
GROUP BY p.product_name
ORDER BY total_revenue DESC;

-- Q3. How many users have signed up for the service and have taken the gold membership?
SELECT COUNT(DISTINCT userid) AS gold_members_count
FROM project.goldusers_signup;

-- Q4 & Q5. What is the total revenue generated from gold users?
SELECT SUM(p.price) AS total_gold_revenue
FROM project.sales s
JOIN project.goldusers_signup g ON s.userid = g.userid
JOIN project.product p ON s.product_id = p.product_id
WHERE s.created_date >= g.gold_signup_date;

-- Q6. Which users have been a gold user for how much time?
SELECT userid, gold_signup_date,
       DATEDIFF(day, gold_signup_date, GETDATE()) AS days_as_gold_member
FROM project.goldusers_signup;

-- Q7. What is the most popular product among gold users?
SELECT TOP 1 p.product_name, COUNT(s.product_id) AS order_count
FROM project.sales s
JOIN project.goldusers_signup g ON s.userid = g.userid
JOIN project.product p ON s.product_id = p.product_id
GROUP BY p.product_name
ORDER BY order_count DESC;

-- Q8. What is the total sales revenue generated in each year?
SELECT YEAR(s.created_date) AS sales_year, SUM(p.price) AS total_revenue
FROM project.sales s
JOIN project.product p ON s.product_id = p.product_id
GROUP BY YEAR(s.created_date)
ORDER BY sales_year;

-- Q9. How has the sales revenue changed over the years?
WITH YearlyRevenue AS (
    SELECT YEAR(s.created_date) AS sales_year, SUM(p.price) AS revenue
    FROM project.sales s
    JOIN project.product p ON s.product_id = p.product_id
    GROUP BY YEAR(s.created_date)
)
SELECT sales_year, revenue,
       LAG(revenue) OVER (ORDER BY sales_year) AS previous_year_revenue,
       ROUND(((revenue - LAG(revenue) OVER (ORDER BY sales_year)) / NULLIF(LAG(revenue) OVER (ORDER BY sales_year), 0)) * 100, 2) AS percentage_change
FROM YearlyRevenue;

-- Q10. What is the average Gold-signup compare to just sign up for the users?
SELECT ROUND((COUNT(g.userid) * 100.0) / COUNT(u.userid), 2) AS gold_conversion_rate_percentage
FROM project.users u
LEFT JOIN project.goldusers_signup g ON u.userid = g.userid;

-- Q11. How many gold members users have ordered how many numbers of times (Before vs After)?
SELECT s.userid,
       COUNT(CASE WHEN s.created_date < g.gold_signup_date THEN 1 END) AS orders_before_gold,
       COUNT(CASE WHEN s.created_date >= g.gold_signup_date THEN 1 END) AS orders_after_gold
FROM project.sales s
JOIN project.goldusers_signup g ON s.userid = g.userid
GROUP BY s.userid;

-- Q12. What is the total amount each customer spend on Online Food Delivery?
SELECT s.userid, SUM(p.price) AS total_amount_spent
FROM project.sales s
JOIN project.product p ON s.product_id = p.product_id
GROUP BY s.userid
ORDER BY total_amount_spent DESC;

-- Q13. What is the frequency of customer visits to the online platform?
SELECT userid, COUNT(DISTINCT created_date) AS total_visits
FROM project.sales
GROUP BY userid
ORDER BY total_visits DESC;

-- Q14. What was the first order purchase by each customer?
WITH RankedSales AS (
    SELECT userid, product_id, created_date,
           RANK() OVER (PARTITION BY userid ORDER BY created_date ASC) AS rnk
    FROM project.sales
)
SELECT r.userid, p.product_name, r.created_date
FROM RankedSales r
JOIN project.product p ON r.product_id = p.product_id
WHERE r.rnk = 1;

-- Q15. What is the most purchase item on the menu and how many times was it purchased by all customers?
SELECT TOP 1 p.product_name, COUNT(s.product_id) AS times_purchased
FROM project.sales s
JOIN project.product p ON s.product_id = p.product_id
GROUP BY p.product_name
ORDER BY times_purchased DESC;

-- Q16. Which item was most popular for each customer?
WITH CustomerPreference AS (
    SELECT userid, product_id, COUNT(product_id) AS cnt,
           RANK() OVER (PARTITION BY userid ORDER BY COUNT(product_id) DESC) AS rnk
    FROM project.sales
    GROUP BY userid, product_id
)
SELECT cp.userid, p.product_name, cp.cnt AS purchase_count
FROM CustomerPreference cp
JOIN project.product p ON cp.product_id = p.product_id
WHERE cp.rnk = 1;

-- Q17. Which item was purchased first by the customer after they become a member?
WITH FirstGoldOrder AS (
    SELECT s.userid, s.product_id, s.created_date,
           RANK() OVER (PARTITION BY s.userid ORDER BY s.created_date ASC) AS rnk
    FROM project.sales s
    JOIN project.goldusers_signup g ON s.userid = g.userid
    WHERE s.created_date >= g.gold_signup_date
)
SELECT f.userid, p.product_name, f.created_date
FROM FirstGoldOrder f
JOIN project.product p ON f.product_id = p.product_id
WHERE f.rnk = 1;

-- Q18. Which item was purchased just before the customer became a member?
WITH LastOrderBeforeGold AS (
    SELECT s.userid, s.product_id, s.created_date,
           RANK() OVER (PARTITION BY s.userid ORDER BY s.created_date DESC) AS rnk
    FROM project.sales s
    JOIN project.goldusers_signup g ON s.userid = g.userid
    WHERE s.created_date < g.gold_signup_date
)
SELECT l.userid, p.product_name, l.created_date
FROM LastOrderBeforeGold l
JOIN project.product p ON l.product_id = p.product_id
WHERE l.rnk = 1;

-- Q19. What is the total orders and amount spent for each member before they become a member?
SELECT s.userid, COUNT(s.product_id) AS total_orders, SUM(p.price) AS total_amount_spent
FROM project.sales s
JOIN project.goldusers_signup g ON s.userid = g.userid
JOIN project.product p ON s.product_id = p.product_id
WHERE s.created_date < g.gold_signup_date
GROUP BY s.userid;

-- Q20. Rank all transactions for each member whenever they are a gold member; for non-gold transactions, mark as 'na'?
SELECT s.userid, s.created_date, p.product_name, g.gold_signup_date,
       CASE 
            WHEN s.created_date >= g.gold_signup_date 
            THEN CAST(RANK() OVER (PARTITION BY s.userid, CASE WHEN s.created_date >= g.gold_signup_date THEN 1 ELSE 0 END ORDER BY s.created_date DESC) AS VARCHAR)
            ELSE 'na' 
       END AS gold_transaction_rank
FROM project.sales s
LEFT JOIN project.goldusers_signup g ON s.userid = g.userid
JOIN project.product p ON s.product_id = p.product_id;
